"""Record to tool: perform a task once on the terminal, get a draft tool definition.

The recorder watches the screens through the screen map. Each time a submit key
(Enter or a function key) is pressed it notes the screen, the values typed into its
input fields, the key, and the screen that came back. Typed values become tool
parameters; the fields on the final screen become outputs. Navigation before the
first work screen collapses into a single `goto`, which the bridge resolves itself.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import Any

import yaml

from .driver import KEYS, Snapshot, TerminalDriver
from .screenmap import ScreenMap

SUBMIT_KEYS = {"ENTER"} | {f"F{i}" for i in range(1, 13)}
NAV_SCREENS = {"SIGNON", "MAIN"}


@dataclass
class Step:
    screen: str
    values: dict[str, str]
    key: str
    result: str | None


@dataclass
class Recorder:
    screen_map: ScreenMap
    driver: TerminalDriver
    steps: list[Step] = field(default_factory=list)
    _shown: dict[str, str] = field(default_factory=dict)  # input values already on screen after the last submit

    def _inputs(self, sid: str, snap: Snapshot) -> dict[str, str]:
        sd = self.screen_map.screens[sid]
        out = {}
        for name, f in sd.inputs():
            if f.hidden:
                continue
            v = snap.text_at(f.row, f.col, f.len).rstrip("_ ").strip()
            if v:
                out[name] = v
        return out

    def send(self, text: str) -> None:
        self.driver.send(text)

    def press(self, key: str) -> Snapshot:
        before = self.driver.settle(quiet=0.1, timeout=3)
        sid = self.screen_map.identify(before)
        if key in SUBMIT_KEYS and sid:
            typed = {k: v for k, v in self._inputs(sid, before).items() if self._shown.get(k) != v}
            self.driver.press(key)
            after = self.driver.settle(quiet=0.15, timeout=10, response_wait=5)
            result = self.screen_map.identify(after)
            self.steps.append(Step(sid, typed, key, result))
            self._shown = self._inputs(result, after) if result else {}
            return after
        self.driver.press(key)
        return self.driver.settle(quiet=0.1, timeout=3)

    def to_tool(self, name: str, description: str = "") -> dict[str, Any]:
        steps = [s for s in self.steps if s.screen not in NAV_SCREENS and not self.screen_map.screens[s.screen].interrupt]
        if not steps:
            raise ValueError("no work screens were recorded")
        params: dict[str, dict[str, Any]] = {}
        flow: list[dict[str, Any]] = [{"goto": steps[0].screen}]
        uses_confirm = False
        for s in steps:
            if s.values:
                fill = {}
                for f, v in s.values.items():
                    pname = f if f not in params else f"{s.screen.lower()}_{f}"
                    fd = self.screen_map.screens[s.screen].fields[f]
                    params[pname] = {"type": "string", "description": f"{f.replace('_', ' ')} (recorded example: {v})"}
                    if fd.pattern:
                        params[pname]["pattern"] = fd.pattern
                    fill[f] = "{" + pname + "}"
                flow.append({"fill": fill})
            flow.append({"press": s.key})
            if s.result:
                flow.append({"expect": [s.result]})
            if s.key == "F10":
                uses_confirm = True
        final = steps[-1].result
        if final and final not in NAV_SCREENS:
            outputs = [n for n, f in self.screen_map.screens[final].fields.items() if not f.input]
            if outputs:
                flow.append({"read": outputs})
            if self.screen_map.screens[final].tables:
                for t in self.screen_map.screens[final].tables:
                    flow.append({"read_table": {"table": t}})
        return {name: {
            "description": description or f"Recorded flow over {', '.join(dict.fromkeys(s.screen for s in steps))}. REVIEW before use.",
            "mode": "write" if uses_confirm else "read",
            "inputs": params,
            "steps": flow,
        }}

    def to_yaml(self, name: str, description: str = "") -> str:
        tool = self.to_tool(name, description)
        header = ("# Draft tool generated by `lbridge record`. Review it before exposing it to agents:\n"
                  "# check parameter names, add patterns, and for write flows split the final confirm key\n"
                  "# into a `confirm:` block so the bridge asks before committing.\n")
        return header + yaml.safe_dump({"tools": tool}, sort_keys=False)


def keys_from_terminal(data: str) -> list[tuple[str, str]]:
    """Split raw terminal input into ('text', chars) and ('key', NAME) events."""
    reverse = {v: k for k, v in KEYS.items()}
    events, i = [], 0
    pattern = re.compile("|".join(re.escape(s) for s in sorted(reverse, key=len, reverse=True)))
    for m in pattern.finditer(data):
        if m.start() > i:
            events.append(("text", data[i:m.start()]))
        events.append(("key", reverse[m.group(0)]))
        i = m.end()
    if i < len(data):
        events.append(("text", data[i:]))
    return events
